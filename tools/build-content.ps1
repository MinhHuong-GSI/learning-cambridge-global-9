# Collects GAME data from the "Tho Quest" *.html files (parent folder) into data/lessons.bundle.js
# Re-run after adding or editing quest files (ASCII-only file: PowerShell 5.1 reads it as ANSI):
#   powershell -ExecutionPolicy Bypass -File tools\build-content.ps1
$ErrorActionPreference = 'Stop'
$appDir = Split-Path -Parent $PSScriptRoot
$srcDir = Split-Path -Parent $appDir
$utf8 = New-Object System.Text.UTF8Encoding($false)
$marker = '// ============ Tho Quest - generic core engine'

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('// AUTO-GENERATED by tools/build-content.ps1 - do not edit; edit the source quest file and re-run.')
$seen = @{}
$count = 0
Get-ChildItem -Path $srcDir -Filter *.html | Sort-Object Name | ForEach-Object {
  $name = $_.Name
  $text = [IO.File]::ReadAllText($_.FullName, $utf8)
  $start = $text.IndexOf('var GAME = {')
  $end = $text.IndexOf($marker)
  if ($start -lt 0 -or $end -lt 0) { Write-Warning "Skipped (no GAME object): $name"; return }
  $m = [regex]::Match($name, 'Unit (\d)(?:\.(\d))?')
  if (-not $m.Success) { Write-Warning "Unit number not found: $name"; return }
  $unit = [int]$m.Groups[1].Value
  if ($name -match 'On Tap') { $id = "u$unit-review"; $type = 'review' }
  elseif ($name -match 'Ket Noi') { $id = "u$unit-connect"; $type = 'connect' }
  elseif ($m.Groups[2].Success) { $id = "u$unit-$($m.Groups[2].Value)"; $type = 'lesson' }
  else { Write-Warning "Unknown lesson type: $name"; return }
  if ($seen.ContainsKey($id)) { Write-Warning "Duplicate $id, skipped: $name (already $($seen[$id]))"; return }
  $seen[$id] = $name
  $obj = $text.Substring($start + 'var GAME = '.Length, $end - $start - 'var GAME = '.Length).Trim()
  if ($obj.EndsWith(';')) { $obj = $obj.Substring(0, $obj.Length - 1) }
  $srcName = $name -replace '\\', '\\' -replace '"', '\"'
  [void]$out.AppendLine("CG9.addLesson({id:`"$id`", unit:$unit, type:`"$type`", src:`"$srcName`", game:$obj});")
  $count++
}
$extra = Join-Path $appDir 'data\extra-lessons'
if (Test-Path $extra) {
  Get-ChildItem -Path $extra -Filter *.js | Sort-Object Name | ForEach-Object {
    [void]$out.AppendLine([IO.File]::ReadAllText($_.FullName, $utf8))
  }
}
[IO.File]::WriteAllText((Join-Path $appDir 'data\lessons.bundle.js'), $out.ToString(), $utf8)
Write-Host "Collected $count lessons into data\lessons.bundle.js"
